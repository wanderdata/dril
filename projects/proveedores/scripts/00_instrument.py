"""Write the Stage 2 instrument (protocol V260721) as a machine-readable YAML file.

Variables, questions, types and value labels come from the variable dictionary
(data/source/diccionario_variables_dril_etapa2_V260721.xlsx). Dependency rules
come from sections 6.2, 12 and 15 of the protocol
(protocol/260721_Protocolo_DRIL_Etapa_2_caracterizacion.md) and are written out
below with their source. The YAML is committed; rerun this script only if the
dictionary or protocol changes.
"""
from pathlib import Path

import pandas as pd
import yaml

HERE = Path(__file__).resolve().parents[1]
DICT = HERE / "data/source/diccionario_variables_dril_etapa2_V260721.xlsx"
OUT = HERE / "instrument/stage2_V260721.yaml"

PREFILLED = ["entidad_id", "entidad_input", "pais", "entidad_nivel", "entidad_tipo",
             "iniciativa_candidata_id", "iniciativa_candidata_nombre"]

# Instrument blocks, protocol section 12.
BLOCKS = {
    "A": ["nombre", "nombre_corto", "entidades_ejecutoras", "tipo_programa", "nivel_programa",
          "programa_madre_nombre", "sector_area", "empresa_ancla", "empresa_ancla_nombre",
          "mecanismo_vinculacion"],
    "B": ["beneficiario_textual", "beneficiario_tipo", "objetivo_textual", "objetivo_corto"],
    "C": ["cobertura_geografica", "anio_inicio", "vigencia"],
    "D": ["presupuesto", "p_moneda", "p_anio", "p_tipo", "reglamento", "reglamento_link"],
    "E": ["acompanamiento_directo", "informacion", "informacion_detalle", "coordinacion",
          "capacitacion", "capacitacion_detalle"],
    "F": ["subsidio", "subsidio_objetivo", "subsidio_beneficiario", "subsidio_corte", "subsidio_monto",
          "subsidio_moneda", "subsidio_anio", "subsidio_tipo", "subsidio_cofinanciamiento",
          "subsidio_cofinanciamiento_prop"],
    "G": ["evaluacion", "evaluacion_tipo", "evaluacion_disponible", "evaluacion_link"],
}

KIND = {  # dictionary "Tipo" -> instrument kind
    "Cadena de texto.": "text",
    "Cadena de texto multivalor.": "multitext",
    "Categórica.": "categorical",
    "Categórica multivalor.": "multicategorical",
    "Numérico.": "numeric",
    "Numérico, año de cuatro dígitos.": "year",
    "Código ISO 4217.": "currency",
    "URL.": "url",
    "Numérico entre 0 y 100.": "percent",
}
# Numeric fields that hold years, per protocol section 12 ("Registra el año").
YEAR_FIELDS = {"p_anio", "subsidio_anio"}

# Rules "if X = value then Y = -88", protocol section 15 items 7-12, plus two rules stated
# only in the coding instructions of section 12 (marked source: "12").
DEPENDENCIES = [
    {"if": "reglamento", "equals": "2", "then_not_applicable": ["reglamento_link"], "source": "15.7"},
    {"if": "informacion", "equals": "2", "then_not_applicable": ["informacion_detalle"], "source": "15.8"},
    {"if": "capacitacion", "equals": "2", "then_not_applicable": ["capacitacion_detalle"], "source": "15.9"},
    {"if": "subsidio", "equals": "2", "then_not_applicable": [
        "subsidio_objetivo", "subsidio_beneficiario", "subsidio_corte", "subsidio_monto",
        "subsidio_moneda", "subsidio_anio", "subsidio_tipo", "subsidio_cofinanciamiento",
        "subsidio_cofinanciamiento_prop"], "source": "15.10"},
    {"if": "evaluacion", "equals": "2", "then_not_applicable": [
        "evaluacion_tipo", "evaluacion_disponible", "evaluacion_link"], "source": "15.11"},
    {"if": "empresa_ancla", "equals": "2", "then_not_applicable": ["empresa_ancla_nombre"], "source": "15.12"},
    {"if": "subsidio_cofinanciamiento", "equals": "2",
     "then_not_applicable": ["subsidio_cofinanciamiento_prop"], "source": "12"},
    {"if": "evaluacion_disponible", "equals": "2", "then_not_applicable": ["evaluacion_link"], "source": "12"},
]


def main():
    d = pd.read_excel(DICT, sheet_name="Diccionario", header=3, dtype=str)
    d.columns = ["var", "question", "tipo", "orig", "label", "definition", "instructions"]
    block_of = {v: b for b, vs in BLOCKS.items() for v in vs}
    variables = []
    for name in [v for vs in BLOCKS.values() for v in vs]:
        rows = d[d["var"] == name]
        if rows.empty:
            raise SystemExit(f"{name} not in dictionary")
        tipo = rows["tipo"].iloc[0].strip()
        kind = KIND[tipo]
        if name in YEAR_FIELDS:
            kind = "year"
        var = {"name": name, "block": block_of[name], "kind": kind,
               "question": rows["question"].iloc[0].strip()}
        if kind in ("categorical", "multicategorical"):
            var["codes"] = {str(r.orig).strip(): str(r.label).strip() for r in rows.itertuples()}
        variables.append(var)

    instrument = {
        "id": "proveedores_stage2",
        "version": "V260721",
        "description": ("Characterisation of public supplier development initiatives in Latin America "
                        "and the Caribbean (Stage 2). Generated by scripts/00_instrument.py from the "
                        "variable dictionary and protocol V260721."),
        "unit_id": "iniciativa_candidata_id",
        "prefilled": PREFILLED,
        "status_suffix": "_status",
        "special_codes": {"not_applicable": "-88", "not_found": "-99"},
        "statuses": ["answered", "inferred", "proxy_used", "partial_answer",
                     "not_found_after_search", "not_applicable", "conflict_unresolved"],
        "status_for_code": {"-88": ["not_applicable"],
                            "-99": ["not_found_after_search", "conflict_unresolved"]},
        "evidence_required_statuses": ["answered", "inferred", "proxy_used", "partial_answer"],
        "multivalue_separator": "|",
        "evidence_fields": ["iniciativa_candidata_id", "variable", "source_url", "source_title",
                            "source_publisher", "source_date", "access_date", "source_locator",
                            "evidence_quote"],
        "evidence_required_fields": ["source_url", "access_date", "source_locator", "evidence_quote"],
        "variables": variables,
        "dependencies": DEPENDENCIES,
    }
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        yaml.safe_dump(instrument, fh, allow_unicode=True, sort_keys=False, width=100)
    print(f"wrote {OUT.relative_to(HERE)}: {len(variables)} variables, {len(DEPENDENCIES)} dependency rules")


if __name__ == "__main__":
    main()
